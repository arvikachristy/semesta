describe('audited country and area reference', () => {
  it('includes the complete documented source scope and explicit UK exceptions', () => {
    const sourceCodes = Object.values(reference).flat();
    expect(sourceCodes).toHaveLength(196);
    expect([...storedCountryIds].sort()).toEqual([...sourceCodes, ...constituentNations].sort());
  });

  it('groups every source entry by UN M49 geography', () => {
    for (const country of storedCountryIds) {
      const code = constituentNations.includes(country) ? CountryList.UnitedKingdom : country;
      expect(reference[countries[country].continent]).toContain(code);
    }
  });
});
